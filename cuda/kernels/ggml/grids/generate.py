"""Writes the IQ grid tables from llama.cpp's `ggml-common.h`.

The tables are data, not code: llama.cpp (MIT, Copyright (c) 2023-2024 The
ggml authors) defines them in `ggml/src/ggml-common.h`; this copies the ones
the CUDA IQ kernels read into `__device__` arrays. Run from this directory:

    python3 generate.py /path/to/llama.cpp/ggml/src/ggml-common.h
"""
import re
import sys

TABLES = {
    'iq2.cuh': [('uint64_t', 'iq2xxs_grid', 256), ('uint64_t', 'iq2xs_grid', 512),
                ('uint64_t', 'iq2s_grid', 1024)],
    'iq13.cuh': [('uint32_t', 'iq3xxs_grid', 256), ('uint32_t', 'iq3s_grid', 512),
                 ('uint64_t', 'iq1s_grid', 2048)],
}
CUDA_TYPES = {'uint64_t': 'unsigned long long', 'uint32_t': 'unsigned int'}
PER_LINE = 16


def table(source, kind, name, size):
    match = re.search(rf'GGML_TABLE_BEGIN\({kind}, {name}, \w+\)(.*?)GGML_TABLE_END', source, re.S)
    values = re.findall(r'0x[0-9a-fA-F]+', match.group(1))
    assert len(values) == size, (name, len(values))
    suffix = 'ull' if kind == 'uint64_t' else 'u'
    lines = [', '.join(v.lower() + suffix for v in values[i:i + PER_LINE])
             for i in range(0, size, PER_LINE)]
    body = ',\n    '.join(lines)
    return f'__device__ const {CUDA_TYPES[kind]} k_{name}[{size}] = {{\n    {body},\n}};\n'


def main():
    source = open(sys.argv[1]).read()
    for path, tables in TABLES.items():
        with open(path, 'w') as out:
            out.write('// Generated by grids/generate.py from llama.cpp v1.0.0 ggml-common.h\n')
            out.write('// (MIT, Copyright (c) 2023-2024 The ggml authors). Do not edit.\n')
            out.write('namespace {\n\n')
            out.write('\n'.join(table(source, *entry) for entry in tables))
            out.write('\n}  // namespace\n')


if __name__ == '__main__':
    main()
