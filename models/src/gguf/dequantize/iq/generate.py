"""Writes llama.cpp's IQ grid tables for every reader from one source.

The tables are data, not code: llama.cpp (MIT, Copyright (c) 2023-2024 The
ggml authors) defines them in `ggml/src/ggml-common.h`. This copies the ones
the IQ decoders read into the host reference's `grids.txt` beside this file,
the CUDA kernels' `__device__` arrays and the Metal decoders' `constant`
arrays. A development tool; run from anywhere:

    python3 generate.py /path/to/llama.cpp/ggml/src/ggml-common.h
"""
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent
LIBMIR = HERE.parents[4]
TABLES = [('uint64_t', 'iq2xxs_grid', 256), ('uint64_t', 'iq2xs_grid', 512),
          ('uint64_t', 'iq2s_grid', 1024), ('uint32_t', 'iq3xxs_grid', 256),
          ('uint32_t', 'iq3s_grid', 512), ('uint64_t', 'iq1s_grid', 2048)]
NOTICE = ('Generated by models/src/gguf/dequantize/iq/generate.py from llama.cpp v1.0.0\n'
          'ggml-common.h (MIT, Copyright (c) 2023-2024 The ggml authors). Do not edit.\n')


def values(source, kind, name, size):
    match = re.search(rf'GGML_TABLE_BEGIN\({kind}, {name}, \w+\)(.*?)GGML_TABLE_END', source, re.S)
    found = [value.lower() for value in re.findall(r'0x[0-9a-fA-F]+', match.group(1))]
    assert len(found) == size, (name, len(found))
    return found


def array(declaration, found, suffix, per_line):
    lines = [', '.join(value + suffix for value in found[i:i + per_line])
             for i in range(0, len(found), per_line)]
    body = ',\n    '.join(lines)
    return f'{declaration} = {{\n    {body},\n}};\n'


def comment(prefix):
    return ''.join(f'{prefix} {line}\n' for line in NOTICE.splitlines())


def host(tables):
    text = comment('#')
    for (_, name, size), found in tables:
        text += f'{name} {size}\n' + '\n'.join(
            ' '.join(found[i:i + 8]) for i in range(0, size, 8)) + '\n'
    return text


def cuda(tables):
    types = {'uint64_t': ('unsigned long long', 'ull'), 'uint32_t': ('unsigned int', 'u')}
    body = '\n'.join(
        array(f'__device__ const {types[kind][0]} k_{name}[{size}]', found, types[kind][1], 16)
        for (kind, name, size), found in tables)
    return comment('//') + 'namespace {\n\n' + body + '\n}  // namespace\n'


def metal(tables):
    types = {'uint64_t': ('ulong', 'ul'), 'uint32_t': ('uint', 'u')}
    return comment('//') + '\n'.join(
        array(f'constant {types[kind][0]} k_{name}[{size}]', found, types[kind][1], 8)
        for (kind, name, size), found in tables)


def main():
    source = open(sys.argv[1]).read()
    tables = [(entry, values(source, *entry)) for entry in TABLES]
    outputs = {
        HERE / 'grids.txt': host(tables),
        LIBMIR / 'cuda/kernels/ggml/grids/iq2.cuh': cuda(tables[:3]),
        LIBMIR / 'cuda/kernels/ggml/grids/iq13.cuh': cuda(tables[3:]),
        LIBMIR / 'metal/kernels/ggml/grids.h': metal(tables),
    }
    for path, text in outputs.items():
        path.write_text(text)


if __name__ == '__main__':
    main()
